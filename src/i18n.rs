//! Texte der Oberfläche – deutsch und englisch, gewählt nach der Systemsprache.

use std::sync::OnceLock;

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    De,
    En,
}

static LANG: OnceLock<Lang> = OnceLock::new();

pub fn init(system_language: &str) {
    let lang = if system_language.to_lowercase().starts_with("de") {
        Lang::De
    } else {
        Lang::En
    };
    let _ = LANG.set(lang);
}

pub fn lang() -> Lang {
    *LANG.get().unwrap_or(&Lang::En)
}

pub fn lang_code() -> &'static str {
    match lang() {
        Lang::De => "de",
        Lang::En => "en",
    }
}

