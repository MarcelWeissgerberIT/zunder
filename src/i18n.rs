/// Text zu einem Schlüssel in der aktiven Sprache.
pub fn t(key: &str) -> &'static str {
    let de = lang() == Lang::De;
    STRINGS
        .iter()
        .find(|(k, _, _)| *k == key)
        .map(|(_, d, e)| if de { *d } else { *e })
        .unwrap_or("")
}

/// Alle Texte als JSON-Objekt für die Oberfläche.
pub fn json() -> String {
    let de = lang() == Lang::De;
    let map: serde_json::Map<String, serde_json::Value> = STRINGS
        .iter()
        .map(|(k, d, e)| (k.to_string(), serde_json::Value::from(if de { *d } else { *e })))
        .collect();
    serde_json::Value::Object(map).to_string()
}
